package com.github.ahatem.qtranslate.core.settings.system

import java.nio.charset.StandardCharsets
import java.util.Base64
import java.util.concurrent.TimeUnit

/**
 * Per-user interactive login task. No stored password and no service/session-0 launch.
 * An elevated application registers Highest; an ordinary application requests Limited.
 * An existing app-owned Highest task keeps that level. This avoids a Run-key launch being
 * silently skipped when the user's executable is configured to require administrator rights.
 */
class WindowsLoginTaskRegistration(
    private val commandRunner: (List<String>) -> WindowsStartupRegistration.CommandResult = ::runCommand,
    private val osName: String = System.getProperty("os.name").orEmpty(),
) {
    /** Only app-owned tasks for the current Windows SID may be created/updated/deleted. */
    fun reconcile(enabled: Boolean, command: String?): Boolean {
        if (!WindowsStartupRegistration.isWindows(osName)) return true
        if (enabled && splitCommand(command) == null) return false
        return execute(script(enabled, command))
    }

    /** A failed update must not replace an existing privileged task with a Run entry. */
    fun isAbsent(): Boolean = execute(script(false, null, probeOnly = true))

    private fun execute(script: String): Boolean {
        val encoded = Base64.getEncoder().encodeToString(script.toByteArray(StandardCharsets.UTF_16LE))
        return runCatching {
            commandRunner(listOf("powershell.exe", "-NoLogo", "-NoProfile", "-NonInteractive",
                "-EncodedCommand", encoded)).exitCode == 0
        }.getOrDefault(false)
    }

    companion object {
        internal const val OWNER_MARKER = "QTranslate managed interactive startup v1"

        /** Commands generated by WindowsStartupRegistration always quote their executable. */
        internal fun splitCommand(command: String?): Pair<String, String>? {
            val match = command?.let { Regex("^\"([^\"]+)\"(?:\\s+(.*))?$").matchEntire(it) } ?: return null
            return match.groupValues[1] to match.groupValues[2]
        }

        private fun literal(value: String): String = "'${value.replace("'", "''")}'"

        /** Public behavior is tested through the encoded argv; no PowerShell runs in unit tests. */
        internal fun script(enabled: Boolean, command: String?, probeOnly: Boolean = false): String {
            val launch = splitCommand(command)
            val executable = launch?.first.orEmpty()
            val arguments = launch?.second.orEmpty()
            val workingDirectory = executable.substringBeforeLast('\\', "")
                .ifEmpty { executable.substringBeforeLast('/', "") }
            return """
                ${'$'}ErrorActionPreference = 'Stop'
                try {
                    ${'$'}identity = [Security.Principal.WindowsIdentity]::GetCurrent()
                    ${'$'}sid = ${'$'}identity.User.Value
                    ${'$'}name = "QTranslate-${'$'}sid"
                    ${'$'}marker = ${literal(OWNER_MARKER)}
                    # A missing task is ordinary; an unreadable root folder must fail.
                    ${'$'}existing = Get-ScheduledTask -ErrorAction Stop | Where-Object { ${'$'}_.TaskPath -eq '\' -and ${'$'}_.TaskName -eq ${'$'}name }
                    if (${'$'}existing -and ${'$'}existing.Description -ne ${'$'}marker) { exit 2 }
                    ${if (probeOnly) "if (${'$'}existing) { exit 1 } else { exit 0 }" else ""}
                    ${if (!enabled) """
                    if (${'$'}existing) {
                        Unregister-ScheduledTask -TaskName ${'$'}name -TaskPath '\' -Confirm:${'$'}false
                    }
                    """ else """
                    ${'$'}exe = ${literal(executable)}
                    ${'$'}arguments = ${literal(arguments)}
                    ${'$'}directory = ${literal(workingDirectory)}
                    if (-not (Test-Path -LiteralPath ${'$'}exe -PathType Leaf)) { exit 3 }
                    ${'$'}principal = New-Object Security.Principal.WindowsPrincipal(${'$'}identity)
                    ${'$'}elevated = ${'$'}principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
                    ${'$'}level = if (${'$'}elevated -or (${'$'}existing -and ${'$'}existing.Principal.RunLevel -eq 'Highest')) { 'Highest' } else { 'Limited' }
                    function Resolve-Sid([string] ${'$'}userId) {
                        if (${'$'}userId -match '^S-1-') { return ${'$'}userId }
                        return ([Security.Principal.NTAccount]::new(${'$'}userId)).Translate([Security.Principal.SecurityIdentifier]).Value
                    }
                    ${'$'}matches = ${'$'}existing -and ${'$'}existing.Actions.Count -eq 1 -and
                        ${'$'}existing.Actions[0].Execute -eq ${'$'}exe -and
                        ${'$'}existing.Actions[0].Arguments -eq ${'$'}arguments -and
                        ${'$'}existing.Actions[0].WorkingDirectory -eq ${'$'}directory -and
                        (Resolve-Sid ${'$'}existing.Principal.UserId) -eq ${'$'}sid -and
                        ${'$'}existing.Principal.LogonType -eq 'Interactive' -and
                        ${'$'}existing.Principal.RunLevel -eq ${'$'}level -and
                        ${'$'}existing.Triggers.Count -eq 1 -and (Resolve-Sid ${'$'}existing.Triggers[0].UserId) -eq ${'$'}sid -and
                        ${'$'}existing.State -ne 'Disabled' -and
                        ${'$'}existing.Settings.ExecutionTimeLimit -eq 'PT0S' -and
                        -not ${'$'}existing.Settings.DisallowStartIfOnBatteries -and
                        -not ${'$'}existing.Settings.StopIfGoingOnBatteries
                    if (-not ${'$'}matches) {
                        ${'$'}actionParameters = @{ Execute = ${'$'}exe; WorkingDirectory = ${'$'}directory }
                        if (${'$'}arguments) { ${'$'}actionParameters.Argument = ${'$'}arguments }
                        ${'$'}action = New-ScheduledTaskAction @actionParameters
                        ${'$'}trigger = New-ScheduledTaskTrigger -AtLogOn -User ${'$'}sid
                        ${'$'}account = New-ScheduledTaskPrincipal -UserId ${'$'}sid -LogonType Interactive -RunLevel ${'$'}level
                        ${'$'}settings = New-ScheduledTaskSettingsSet -ExecutionTimeLimit ([TimeSpan]::Zero) -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -MultipleInstances IgnoreNew
                        Register-ScheduledTask -TaskName ${'$'}name -TaskPath '\' -Description ${'$'}marker -Action ${'$'}action -Trigger ${'$'}trigger -Principal ${'$'}account -Settings ${'$'}settings -Force | Out-Null
                    }
                    """}
                    exit 0
                } catch { exit 1 }
            """.trimIndent()
        }

        private fun runCommand(argv: List<String>): WindowsStartupRegistration.CommandResult {
            val process = ProcessBuilder(argv).redirectErrorStream(true).start()
            return try {
                if (!process.waitFor(20, TimeUnit.SECONDS)) {
                    process.destroyForcibly()
                    WindowsStartupRegistration.CommandResult(-1, "timeout")
                } else WindowsStartupRegistration.CommandResult(process.exitValue(), "")
            } catch (interrupted: InterruptedException) {
                process.destroyForcibly()
                Thread.currentThread().interrupt()
                WindowsStartupRegistration.CommandResult(-1, "interrupted")
            } finally {
                process.inputStream.close()
            }
        }
    }
}
